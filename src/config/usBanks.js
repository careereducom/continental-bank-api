/**
 * Look up a bank name by routing number.
 * Returns the bank name, or a generic label if unknown.
 */
function resolveBank(routingNumber) {
  if (!routingNumber) return 'Beneficiary Bank';
  const key = String(routingNumber).trim();
  return US_BANKS[key] || `Bank (routing ${key})`;
}

/**
 * Return true if this is our own routing number.
 */
function isOurBank(routingNumber) {
  return String(routingNumber).trim() === '021407912';
}

