function hashNumber(str) {
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    hash = (hash * 31 + str.charCodeAt(i)) >>> 0;
  }
  return hash;
}

function resolveExternalName(accountNumber) {
  if (!accountNumber) return 'UNKNOWN BENEFICIARY';
  return EXTERNAL_NAMES[hashNumber(String(accountNumber)) % EXTERNAL_NAMES.length];
}

